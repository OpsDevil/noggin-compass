_language = "en"


def set_language(language: str) -> None:
    global _language
    if language not in LANGUAGES:
        raise ValueError(f"language must be one of {', '.join(LANGUAGES)}")
    _language = language


def get_language() -> str:
    return _language


def hours_text(hours: float) -> str:
    """A number of hours in words, in the current language: "24 hours", "24 часа", "12 часов"."""
    if _language != "ru":
        return f"{hours:g} {'hour' if hours == 1 else 'hours'}"
    if not float(hours).is_integer():
        return f"{hours:g} часа"
    n = int(hours)
    if n % 10 == 1 and n % 100 != 11:
        return f"{n} час"
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return f"{n} часа"
    return f"{n} часов"


def t(key: str, /, **kwargs) -> str:
    text = MESSAGES[_language].get(key) or MESSAGES["en"][key]
    return text.format(**kwargs) if kwargs else text
